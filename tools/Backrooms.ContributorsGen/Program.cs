using System.Diagnostics;
using System.Text.Json;

if (args.Length != 3)
{
    Console.Error.WriteLine("Usage: Backrooms.ContributorsGen <repo-root> <cs-output> <json-output>");
    return 2;
}

var repoRoot = Path.GetFullPath(args[0]);
var csOutput = Path.GetFullPath(args[1]);
var jsonOutput = Path.GetFullPath(args[2]);
var people = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);

try
{
    var psi = new ProcessStartInfo("git")
    {
        WorkingDirectory = repoRoot,
        UseShellExecute = false,
        RedirectStandardOutput = true,
        RedirectStandardError = true,
        CreateNoWindow = true
    };
    psi.ArgumentList.Add("shortlog");
    psi.ArgumentList.Add("-s");
    psi.ArgumentList.Add("-n");
    psi.ArgumentList.Add("--all");
    psi.ArgumentList.Add("--format=%aN");
    using var process = Process.Start(psi) ?? throw new InvalidOperationException("Cannot start git.");
    var output = process.StandardOutput.ReadToEnd();
    var error = process.StandardError.ReadToEnd();
    process.WaitForExit();
    if (process.ExitCode != 0)
        throw new InvalidOperationException(error);

    foreach (var raw in output.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
    {
        var line = raw.Trim();
        var split = line.IndexOfAny([' ', '\t']);
        if (split <= 0 || !int.TryParse(line[..split].Trim(), out var count)) continue;
        var name = line[split..].Trim();
        if (name.Length == 0) continue;
        people[name] = people.TryGetValue(name, out var old) ? old + count : count;
    }
}
catch (Exception ex)
{
    Console.Error.WriteLine($"Contributor generation warning: {ex.Message}");
}

var ordered = people
    .Select(p => new Contributor(p.Key, p.Value))
    .OrderByDescending(p => p.Commits)
    .ThenBy(p => p.Name, StringComparer.OrdinalIgnoreCase)
    .ToArray();

var json = JsonSerializer.Serialize(ordered, new JsonSerializerOptions { WriteIndented = true });
Directory.CreateDirectory(Path.GetDirectoryName(jsonOutput)!);
File.WriteAllText(jsonOutput, json);

var csharpLiteral = JsonSerializer.Serialize(json);
var source = $"""// <auto-generated />\nnamespace Backrooms.Launcher.Generated;\n\npublic static class GeneratedContributors\n{{\n    public const string Json = {csharpLiteral};\n}}\n""";
Directory.CreateDirectory(Path.GetDirectoryName(csOutput)!);
File.WriteAllText(csOutput, source);
Console.WriteLine($"Generated {ordered.Length} contributor(s).");
return 0;

internal sealed record Contributor(string Name, int Commits);
